const buildImageUrl = (label) => `/images/${LOCAL_IMAGE_ALIASES[label] || 'book'}.png`;

const inferDifficulty = (units) => {
  if (units.length >= 4 || units.some((unit) => unit.length >= 5)) return 'HARD';
  if (units.length === 3 || units.some((unit) => unit.length >= 4)) return 'MEDIUM';
  return 'EASY';
};

const inferType = (units) => {
  if (units.length >= 4) return 'MIXED_CLUSTER';
  if (units.length === 3) return 'OPEN_OPEN_CLOSED';
  return 'MIXED';
};

const buildLangLevels = (lang, entries) =>
  entries.map(([text, imageLabel, units], index) =>
    level(
      `syll-${lang.toLowerCase()}-${index + 1}`,
      text,
      buildImageUrl(imageLabel),
      units,
      inferDifficulty(units),
      inferType(units)
    )
  );

